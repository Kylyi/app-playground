  await expect(page.getByTestId('main-bar-title-append')).toHaveText('Append')
  await expect(page.getByTestId('main-bar-right')).toHaveText('Right')
  await expect(page.getByTestId('main-bar-inner')).toHaveText('Inner')
  await expect(page.getByTestId('presentation-breadcrumbs').getByRole('link', { name: 'Library', exact: true }))
    .toHaveAttribute('href', '/library')
  await expect(page.getByTestId('presentation-breadcrumbs')).toContainText('Current page')
  await expect(page.getByTestId('breadcrumbs-append')).toHaveText('Append')
  await expect(page.getByTestId('breadcrumbs-right')).toHaveText('Right')
  await expect(page.getByTestId('presentation-banner')).toContainText('Banner content')
  await expect(page.getByTestId('presentation-banner').locator('.badge')).toHaveText('1')
  await expect(page.getByTestId('presentation-section')).toContainText('Presentation section')
  await expect(page.getByTestId('presentation-section')).toContainText('Section subtitle')
  await expect(page.getByTestId('section-content')).toHaveText('Section content')
