test('MiniCard and InputBlock preserve fallback, custom readonly slots and editable values', async ({ page }, testInfo) => {
  await page.goto('/cs-CZ/vapor-value-contracts')
  const target = page.getByTestId('value-contracts')
  await expect(target).toHaveAttribute('data-ready', 'true')
  const readonly = page.locator('[data-testid="input-block"].input-block__readonly')
  await expect(readonly).toContainText('Current')
  await expect(page.getByTestId('mini-card')).toContainText('Previous')
  await expect(page.locator('[data-testid="custom-input-block"].input-block__readonly')).toContainText('Custom: Current')
  await captureState({ page, testInfo, target, state: 'values-readonly', families: ['Card', 'InputBlock'] })
  await page.getByTestId('mini-card').getByRole('button').click()
  await expect(page.locator('.menu')).toContainText('Original')
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Empty value', exact: true }).click()
  await expect(readonly).toContainText('Empty')
  await page.getByRole('button', { name: 'Zero value', exact: true }).click()
  await expect(readonly).toContainText('0')
  await expect(page.getByTestId('mini-card')).toContainText('0')
  await page.getByRole('button', { name: 'Toggle editable', exact: true }).click()
  await page.getByTestId('block-editor').fill('Edited')
  await expect(page.getByTestId('custom-block-editor')).toBeVisible()
  await page.getByRole('button', { name: 'Toggle editable', exact: true }).click()
  await expect(readonly).toContainText('Edited')
  await page.getByRole('button', { name: 'Toggle owner', exact: true }).click()
  await expect(page.getByTestId('value-contracts-owner')).toHaveCount(0)
  await page.getByRole('button', { name: 'Toggle owner', exact: true }).click()
  await expect(readonly).toContainText('Edited')
})

test('relative time defaults its unit, preserves exact/unit preferences across clear and accepts replacement', async ({ page }, testInfo) => {
  await page.goto('/en-US/vapor-value-contracts')
  const target = page.getByTestId('value-contracts')
  await expect(target).toHaveAttribute('data-ready', 'true')
  const field = page.getByTestId('relative-time')
  const input = field.locator('input')
  await page.getByRole('button', { name: 'Focus relative time', exact: true }).click()
  await expect(input).toBeFocused()
  await input.fill('3')
  await expect(page.getByTestId('relative-value')).toHaveText('3m')
  await field.getByRole('button', { name: 'months', exact: true }).click()
  await page.locator('.menu').getByRole('button', { name: 'Weeks', exact: true }).click()
  await expect(page.getByTestId('relative-value')).toHaveText('3w')
  const exact = field.getByRole('button', { name: 'exact', exact: true })
  await exact.click()
  await expect(page.getByTestId('relative-value')).toHaveText('3we')
  await captureState({ page, testInfo, target, state: 'relative-exact', families: ['QueryBuilder', 'Inputs'] })
  await input.fill('')
  await expect(page.getByTestId('relative-value')).toHaveText('empty')
  await input.fill('4')
  await expect(page.getByTestId('relative-value')).toHaveText('4we')
  await page.getByRole('button', { name: 'Replace relative time', exact: true }).click()
  await expect(input).toHaveValue('2')
  await expect(page.getByTestId('relative-value')).toHaveText('2we')
  await page.getByRole('button', { name: 'Toggle owner', exact: true }).click()
  await page.getByRole('button', { name: 'Toggle owner', exact: true }).click()
  await expect(input).toHaveValue('2')
})

test('standalone month selector crosses the year boundary and selects from its anchored menu', async ({ page }, testInfo) => {
  await page.goto('/cs-CZ/vapor-value-contracts')
  const target = page.getByTestId('value-contracts')
  await expect(target).toHaveAttribute('data-ready', 'true')
  const field = page.getByTestId('month-selector')
  const buttons = field.getByRole('button')
  await expect(page.getByTestId('month-value')).toHaveText('2026-12')
  await buttons.last().click()
  await expect(page.getByTestId('month-value')).toHaveText('2027-01')
  await buttons.first().click()
  await expect(page.getByTestId('month-value')).toHaveText('2026-12')
  await buttons.nth(1).click()
  await expect(page.locator('.menu')).toBeVisible()
  await captureState({ page, testInfo, target: page.locator('.menu'), state: 'month-open', families: ['MonthSelector', 'Menu'] })
  await page.locator('.menu').getByRole('button', { name: 'červen', exact: true }).click()
  await expect(page.getByTestId('month-value')).toHaveText('2026-06')
  await expect(page.locator('.menu')).toHaveCount(0)
})

test('value contracts render fallback values and localized navigation without JavaScript', async ({ browser, baseURL }) => {
  const context = await createObservedContext(browser, { baseURL, javaScriptEnabled: false })
  try {
    const page = await context.newPage()
    await page.goto('/cs-CZ/vapor-value-contracts')
    await expect(page.locator('[data-testid="input-block"].input-block__readonly')).toContainText('Current')
    await expect(page.getByTestId('mini-card')).toContainText('Previous')
    await expect(page.getByTestId('month-value')).toHaveText('2026-12')
    // The mobile navigation is inert until the client mounts. Its SSR href
    // must still be localized when JavaScript is disabled.
    await expect(page.getByRole('link', { name: 'MiniCard a InputBlock · hodnoty', exact: true, includeHidden: true }))
      .toHaveAttribute('href', '/cs-CZ/vapor-value-contracts')
  } finally {
    await context.close()
  }
})
