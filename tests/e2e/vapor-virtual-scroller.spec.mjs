import { expect, test } from '@playwright/test'
import { assertRendererDiagnostics, createObservedContext } from './renderer-diagnostics.mjs'

assertRendererDiagnostics(test)

test('the default SSR estimate hydrates and client remounts fill resized and hidden viewports', async ({ browser, page, baseURL }) => {
  const path = '/cs-CZ/vapor-virtual-scroller?estimate=auto'
  const context = await createObservedContext(browser, { baseURL, javaScriptEnabled: false })
  try {
    const server = await context.newPage()
    await server.goto(path)
    await expect(server.getByTestId('primary-scroller').locator('.virtual-scroll__row')).toHaveCount(68)
    const link = server.getByRole('link', { name: 'VirtualScroller · odhad SSR a viewport', exact: true })
    await expect(link).toHaveAttribute('href', path)
    await link.click()
    await expect(server.getByTestId('primary-scroller').locator('[data-index="0"]')).toContainText('Row 0')
  } finally {
    await context.close()
  }
  await page.goto(path)
  await expect(page.getByTestId('virtual-example')).toHaveAttribute('data-ready', 'true')
  const primary = page.getByTestId('primary-scroller')
  for (let cycle = 0; cycle < 3; cycle++) {
    await expect(primary.locator('.virtual-scroll__row')).toHaveCount(10)
    // An actual viewport larger than the SSR estimate must fill completely.
    await page.getByRole('button', { name: 'Set tall viewport', exact: true }).click()
    await expect(primary).toHaveCSS('height', '2800px')
    await expect(primary.locator('[data-index="87"]')).toBeVisible()
    await page.getByRole('button', { name: 'Hide viewport', exact: true }).click()
    await expect(primary).toBeHidden()
    await page.getByRole('button', { name: 'Show small viewport', exact: true }).click()
    await expect(primary).toHaveCSS('height', '96px')
    await expect(primary.locator('[data-index="0"]')).toBeVisible()
    await expect(primary.locator('.virtual-scroll__row')).toHaveCount(6)
    await page.getByRole('button', { name: 'Toggle virtual owner', exact: true }).click()
    await expect(primary).toHaveCount(0)
    await page.getByRole('button', { name: 'Toggle virtual owner', exact: true }).click()
    await expect(primary.locator('.virtual-scroll__row')).toHaveCount(6)
    await page.getByRole('button', { name: 'Reset viewport', exact: true }).click()
  }
  await expect(primary.locator('.virtual-scroll__row')).toHaveCount(10)
})

test('a VDOM root owner receives the Vapor viewport attrs, DOM ref and scroll API', async ({ page }) => {
  const problems = []
  page.on('pageerror', error => problems.push(error.message))
  page.on('console', message => {
    if (/hydration|no active component/i.test(message.text())) {
      problems.push(message.text())
    }
  })
  await page.goto('/cs-CZ/vapor-virtual-scroller?mode=vdom')
  const viewport = page.getByTestId('mixed-scroller')
  await expect(viewport).toHaveAttribute('data-ready', 'true')
  await expect(viewport).toHaveAttribute('data-element-matches', 'true')
  await expect(viewport).toHaveAttribute('aria-label', 'Mixed owner scroller')
  await expect(viewport).toHaveClass(/mixed-consumer/)
  await expect(viewport).toHaveCSS('height', '220px')
  await expect(viewport).toHaveCSS('width', '320px')
  expect(await viewport.evaluate(el => el.parentElement.dataset.testid)).toBe('virtual-example')
  const firstRow = viewport.locator('.virtual-scroll__row').first()
  const rowBox = await firstRow.boundingBox()
  const buttonBox = await firstRow.getByRole('button').boundingBox()
  expect(buttonBox.y).toBeGreaterThanOrEqual(rowBox.y)
  expect(buttonBox.y + buttonBox.height).toBeLessThanOrEqual(rowBox.y + rowBox.height)
  await viewport.getByRole('button', { name: 'Mixed row 0', exact: true }).click()
  await expect(viewport).toBeFocused()
  await expect(viewport.getByRole('button', { name: 'Mixed row 60', exact: true })).toBeVisible()
  await expect.poll(async () => Number(await viewport.getAttribute('data-start-index'))).toBeGreaterThan(55)
  await viewport.getByRole('button', { name: 'Mixed row 60', exact: true }).click()
  await expect(viewport.getByRole('button', { name: 'Mixed row 0', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Toggle virtual owner', exact: true }).click()
  await expect(viewport).toHaveCount(0)
  await page.getByRole('button', { name: 'Toggle virtual owner', exact: true }).click()
  await expect(viewport).toHaveAttribute('data-element-matches', 'true')
  expect(problems).toEqual([])
})

test('virtual rows measure growth and shrink without affecting another scroller', async ({ page }) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => {
    if (/hydration.*mismatch/i.test(message.text())) {
      errors.push(message.text())
    }
  })
  await page.goto('/cs-CZ/vapor-virtual-scroller')
  await expect(page.getByTestId('virtual-example')).toHaveAttribute('data-ready', 'true')
  const primary = page.getByTestId('primary-scroller')
  const secondary = page.getByTestId('secondary-scroller')
  const row = (scroller, id) => scroller.locator(`.virtual-scroll__row[data-key="${id}"]`)
  await expect(primary).toHaveClass(/(?:^|\s)is-virtual(?:\s|$)/)
  await expect.poll(() => primary.locator('.virtual-scroll__row').count()).toBeLessThan(30)
  await expect(row(primary, 0)).toHaveCSS('height', '32px')
  await page.getByRole('button', { name: 'Toggle heights', exact: true }).click()
  await expect(row(primary, 0)).toHaveCSS('height', '112px')
  await expect.poll(() => row(primary, 1).evaluate(el => el.getBoundingClientRect().top - el.previousElementSibling.getBoundingClientRect().bottom)).toBe(0)
  await expect(row(secondary, 0)).toHaveCSS('height', '32px')
  await expect(row(secondary, 1)).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 32)')
  await page.getByRole('button', { name: 'Toggle heights', exact: true }).click()
  await expect(row(primary, 0)).toHaveCSS('height', '32px')
  await expect(row(primary, 1)).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 32)')

  await page.getByRole('button', { name: 'Scroll to row 60', exact: true }).click()
  await expect(row(primary, 60)).toBeVisible()
  await expect.poll(async () => Number(await page.getByTestId('start-index').textContent())).toBeGreaterThan(55)
  await page.getByRole('button', { name: 'Render viewport only', exact: true }).click()
  await expect.poll(async () => Number(await page.getByTestId('visible-result').textContent())).toBe(60)
  await expect(row(primary, 0)).toHaveCount(0)
  await page.getByRole('button', { name: 'Clear rendered rows', exact: true }).click()
  await expect(primary.locator('.virtual-scroll__row')).toHaveCount(0)
  await page.getByRole('button', { name: 'Rerender rows', exact: true }).click()
  await expect(row(primary, 60)).toBeVisible()
  await page.getByRole('button', { name: 'Toggle heights', exact: true }).click()
  await expect(row(primary, 60)).toHaveCSS('height', '112px')
  await expect.poll(() => row(primary, 61).evaluate(el => el.getBoundingClientRect().top - el.previousElementSibling.getBoundingClientRect().bottom)).toBe(0)
  await expect(row(secondary, 1)).toHaveCSS('transform', 'matrix(1, 0, 0, 1, 0, 32)')
  await page.getByRole('button', { name: 'Append rows', exact: true }).click()
  await page.getByRole('button', { name: 'Scroll to bottom', exact: true }).click()
  await expect(row(primary, 119)).toBeVisible()
  await page.getByRole('button', { name: 'Clear data', exact: true }).click()
  await expect(primary.locator('.virtual-scroll__row')).toHaveCount(0)
  await expect(primary.locator('.virtual-scroll__content')).toHaveCSS('min-height', '0px')
  await page.getByRole('button', { name: 'Append rows', exact: true }).click()
  await page.getByRole('button', { name: 'Scroll to top', exact: true }).click()
  await expect(row(primary, 0)).toBeVisible()
  await page.getByRole('button', { name: 'Toggle virtual owner', exact: true }).click()
  await expect(primary).toHaveCount(0)
  await page.getByRole('button', { name: 'Toggle heights', exact: true }).click()
  await page.getByRole('button', { name: 'Toggle virtual owner', exact: true }).click()
  await expect(row(primary, 0)).toHaveCSS('height', '32px')
  expect(errors).toEqual([])
})

test('virtual scroller SSR and small-list fallback preserve slots and navigation', async ({ browser, baseURL }) => {
  const context = await createObservedContext(browser, { baseURL, javaScriptEnabled: false })
  try {
    const page = await context.newPage()
    await page.goto('/cs-CZ/vapor-virtual-scroller?small=true')
    await expect(page.getByTestId('primary-scroller').locator('.virtual-scroll__row')).toHaveCount(6)
    await expect(page.getByTestId('inner-content')).toHaveText('Inner content')
    await expect(page.getByRole('link', { name: 'VirtualScroller · bez virtualizace', exact: true }))
      .toHaveAttribute('href', '/cs-CZ/vapor-virtual-scroller?small=true')
    await page.goto('/cs-CZ/vapor-virtual-scroller')
    await expect(page.getByTestId('primary-scroller').locator('.virtual-scroll__row')).toHaveCount(8)
    await expect(page.getByRole('link', { name: 'VirtualScroller · měření řádků', exact: true }))
      .toHaveAttribute('href', '/cs-CZ/vapor-virtual-scroller')
    const link = page.getByRole('link', { name: 'VirtualScroller · smíšený vlastník', exact: true })
    await expect(link).toHaveAttribute('href', '/cs-CZ/vapor-virtual-scroller?mode=vdom')
    await link.click()
    const mixed = page.getByTestId('mixed-scroller')
    await expect(mixed.locator('.virtual-scroll__row')).toHaveCount(8)
    await expect(mixed).toHaveAttribute('data-ready', 'false')
    await expect(mixed).toHaveClass(/mixed-consumer/)
    await expect(mixed).toHaveCSS('height', '220px')
  } finally {
    await context.close()
  }
})
